library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

entity BCD_4dig_tb is
--  Port ( );
end BCD_4dig_tb;

architecture tb of BCD_4dig_tb is

component BCD_4digits is
    Port(
        i_a0, i_a1, i_a2, i_a3 : in std_logic_vector(3 downto 0);
        i_b0, i_b1, i_b2, i_b3 : in std_logic_vector(3 downto 0);
        o_bcd0, o_bcd1, o_bcd2, o_bcd3 : out std_logic_vector(3 downto 0);
        o_bcd_final : out std_logic
    );
end component;

signal i_a0, i_a1, i_a2, i_a3 : std_logic_vector(3 downto 0):=(others => '0');
signal i_b0, i_b1, i_b2, i_b3 : std_logic_vector(3 downto 0):=(others => '0');
signal o_bcd0,o_bcd1,o_bcd2,o_bcd3: std_logic_vector(3 downto 0):= (others => '0');
signal o_bcd_final :std_logic:='0';
constant CLOCK_PERIOD : time := 10 ns;

begin

DUT : BCD_4digits
    port map(
        i_a0        => i_a0,
        i_a1        => i_a1,
        i_a2        => i_a2,
        i_a3        => i_a3,
        i_b0        => i_b0,
        i_b1        => i_b1,
        i_b2        => i_b2,
        i_b3        => i_b3,
        o_bcd0      => o_bcd0,
        o_bcd1      => o_bcd1,
        o_bcd2      => o_bcd2,
        o_bcd3      => o_bcd3,
        o_bcd_final => o_bcd_final
    );


    stimulus : process
    begin
        ----------------------------------------------------------------
        -- TEST 1: 0000 + 0000 = 0000
        ----------------------------------------------------------------
        i_a3 <= "0000"; i_a2 <= "0000"; i_a1 <= "0000"; i_a0 <= "0000";
        i_b3 <= "0000"; i_b2 <= "0000"; i_b1 <= "0000"; i_b0 <= "0000";
        wait for 2*CLOCK_PERIOD ;
        ----------------------------------------------------------------
        -- TEST 2: 0001 + 0002 = 0003
        ----------------------------------------------------------------
        i_a3 <= "0000"; i_a2 <= "0000"; i_a1 <= "0000"; i_a0 <= "0001";
        i_b3 <= "0000"; i_b2 <= "0000"; i_b1 <= "0000"; i_b0 <= "0010";
        wait for 2*CLOCK_PERIOD ;
        ----------------------------------------------------------------
        -- TEST 3: 0005 + 0004 = 0009
        ----------------------------------------------------------------
        i_a3 <= "0000"; i_a2 <= "0000"; i_a1 <= "0000"; i_a0 <= "0101";
        i_b3 <= "0000"; i_b2 <= "0000"; i_b1 <= "0000"; i_b0 <= "0100";
         wait for 2*CLOCK_PERIOD ;
        ----------------------------------------------------------------
        -- TEST 4: 0005 + 0005 = 0010
        ----------------------------------------------------------------
        i_a3 <= "0000"; i_a2 <= "0000"; i_a1 <= "0000"; i_a0 <= "0101";
        i_b3 <= "0000"; i_b2 <= "0000"; i_b1 <= "0000"; i_b0 <= "0101";
        wait for 2*CLOCK_PERIOD ;

        ----------------------------------------------------------------
        -- TEST 5: 0009 + 0001 = 0010
        ----------------------------------------------------------------
        i_a3 <= "0000"; i_a2 <= "0000"; i_a1 <= "0000"; i_a0 <= "1001";
        i_b3 <= "0000"; i_b2 <= "0000"; i_b1 <= "0000"; i_b0 <= "0001";
        wait for 2*CLOCK_PERIOD ;

        ----------------------------------------------------------------
        -- TEST 6: 0099 + 0001 = 0100
        ----------------------------------------------------------------
        i_a3 <= "0000"; i_a2 <= "0000"; i_a1 <= "1001"; i_a0 <= "1001";
        i_b3 <= "0000"; i_b2 <= "0000"; i_b1 <= "0000"; i_b0 <= "0001";
        wait for 2*CLOCK_PERIOD ;
        ----------------------------------------------------------------
        -- TEST 7: 0999 + 0001 = 1000
        ----------------------------------------------------------------
        i_a3 <= "0000"; i_a2 <= "1001"; i_a1 <= "1001"; i_a0 <= "1001";
        i_b3 <= "0000"; i_b2 <= "0000"; i_b1 <= "0000"; i_b0 <= "0001";
        wait for 2*CLOCK_PERIOD ;

        ----------------------------------------------------------------
        -- TEST 8: 1234 + 4321 = 5555
        ----------------------------------------------------------------
        i_a3 <= "0001"; i_a2 <= "0010"; i_a1 <= "0011"; i_a0 <= "0100";
        i_b3 <= "0100"; i_b2 <= "0011"; i_b1 <= "0010"; i_b0 <= "0001";
        wait for 2*CLOCK_PERIOD ;

        ----------------------------------------------------------------
        -- TEST 9: 5678 + 1234 = 6912
        ----------------------------------------------------------------
        i_a3 <= "0101"; i_a2 <= "0110"; i_a1 <= "0111"; i_a0 <= "1000";
        i_b3 <= "0001"; i_b2 <= "0010"; i_b1 <= "0011"; i_b0 <= "0100";
        wait for 2*CLOCK_PERIOD ;
    
        ----------------------------------------------------------------
        -- TEST 10: 9999 + 0001 = 10000
        ----------------------------------------------------------------
        i_a3 <= "1001"; i_a2 <= "1001"; i_a1 <= "1001"; i_a0 <= "1001";
        i_b3 <= "0000"; i_b2 <= "0000"; i_b1 <= "0000"; i_b0 <= "0001";
        wait for 2*CLOCK_PERIOD ;
        
        end process;  
end tb;
